create table if not exists public.libros (
  id bigint generated by default as identity primary key,
  titulo varchar(120) not null,
  autor varchar(120) not null,
  categoria varchar(30) not null,
  etiqueta varchar(40) not null,
  saga varchar(120) not null default 'Independiente',
  imagen text not null,
  valoracion numeric(2, 1) not null check (valoracion between 0 and 5),
  opinion varchar(1500) not null,
  puntos_destacados text[] not null default '{}',
  contiene_spoilers boolean not null default false,
  descripcion varchar(1500) not null,
  unique (titulo, autor)
);

create table if not exists public.administradores (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.libros enable row level security;
alter table public.administradores enable row level security;

create or replace function public.es_administrador()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.administradores
    where user_id = auth.uid()
  );
$$;

revoke all on function public.es_administrador() from public;
grant execute on function public.es_administrador() to authenticated;

drop policy if exists "Lectura pública de libros" on public.libros;
create policy "Lectura pública de libros"
on public.libros for select
using (true);

drop policy if exists "Administradores añaden libros" on public.libros;
create policy "Administradores añaden libros"
on public.libros for insert to authenticated
with check (public.es_administrador());

drop policy if exists "Administradores editan libros" on public.libros;
create policy "Administradores editan libros"
on public.libros for update to authenticated
using (public.es_administrador())
with check (public.es_administrador());

drop policy if exists "Administradores eliminan libros" on public.libros;
create policy "Administradores eliminan libros"
on public.libros for delete to authenticated
using (public.es_administrador());

drop policy if exists "Administrador consulta su permiso" on public.administradores;
create policy "Administrador consulta su permiso"
on public.administradores for select to authenticated
using (user_id = auth.uid());

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'portadas',
