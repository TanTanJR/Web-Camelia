  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Lectura pública de portadas" on storage.objects;
create policy "Lectura pública de portadas"
on storage.objects for select
using (bucket_id = 'portadas');

drop policy if exists "Administradores suben portadas" on storage.objects;
create policy "Administradores suben portadas"
on storage.objects for insert to authenticated
with check (bucket_id = 'portadas' and public.es_administrador());

drop policy if exists "Administradores actualizan portadas" on storage.objects;
create policy "Administradores actualizan portadas"
on storage.objects for update to authenticated
using (bucket_id = 'portadas' and public.es_administrador())
with check (bucket_id = 'portadas' and public.es_administrador());

drop policy if exists "Administradores eliminan portadas" on storage.objects;
create policy "Administradores eliminan portadas"
on storage.objects for delete to authenticated
using (bucket_id = 'portadas' and public.es_administrador());

